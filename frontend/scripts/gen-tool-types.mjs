#!/usr/bin/env node
// gen-tool-types — generate strict TS types from the checked-in
// tool-catalog snapshot (Layer 3 of auto-tool-specs).
//
// Reads:  src/lib/generated/toolCatalog.snapshot.json
// Writes: src/lib/generated/tools.gen.ts
//
// Why a snapshot and not a live fetch at build time?
// - Builds are reproducible from git checkout alone — no running
//   backend required for `npm run build`.
// - The snapshot is reviewable: schema drift shows up in PRs.
//
// To refresh the snapshot, run `npm run sync-tools` (separate script,
// requires a running backend + a service token).
//
// The generated file is .gitignored (regenerated on every build) and
// contains:
//   - ToolName: string union of every tool's name
//   - ToolInputsMap: name → inputs interface (strict properties from
//     input_schema, with required vs optional, types projected from
//     JSON Schema)
//   - ToolInputs<N>: helper alias
//   - TOOL_NAMES: readonly array for runtime enumeration
//
// Consumed by lib/typedInvoke.ts to give frontend code compile-time
// validation when calling /api/invoke.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SNAPSHOT = resolve(__dirname, "../src/lib/generated/toolCatalog.snapshot.json");
const OUT = resolve(__dirname, "../src/lib/generated/tools.gen.ts");

// ─────────────────────────────────────────────────────────────────────
// JSON Schema → TS type projection
//
// Kept intentionally narrow:
//   string  → string (or "a" | "b" union for enums)
//   integer → number
//   number  → number
//   boolean → boolean
//   array   → T[] (recurses on items)
//   object  → Record<string, unknown> (most tools take flat inputs;
//             nested object types are too variable to project safely)
//   anything else / missing type → unknown
// ─────────────────────────────────────────────────────────────────────

function jsonSchemaToTs(schema) {
  if (!schema || typeof schema !== "object") return "unknown";
  // Enum wins regardless of declared type — string literal union.
  if (Array.isArray(schema.enum) && schema.enum.length > 0) {
    return schema.enum
      .map((v) => (typeof v === "string" ? JSON.stringify(v) : String(v)))
      .join(" | ");
  }
  const t = schema.type;
  if (t === "string") return "string";
  if (t === "integer" || t === "number") return "number";
  if (t === "boolean") return "boolean";
  if (t === "array") {
    const inner = jsonSchemaToTs(schema.items ?? {});
    // Wrap union item types in parens so T1 | T2[] doesn't parse as T1 | (T2[]).
    return /\|/.test(inner) ? `(${inner})[]` : `${inner}[]`;
  }
  if (t === "object") return "Record<string, unknown>";
  return "unknown";
}

function tsIdent(key) {
  // Keys with non-identifier chars get quoted. JSON Schema property keys
  // are pretty arbitrary in the XCO catalog ("fabric-name", "fabric.name"
  // etc.) so this is needed in practice.
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function escapeBlockComment(s) {
  return String(s).replace(/\*\//g, "*\\/");
}

function buildInputsInterface(tool) {
  const sch = tool.input_schema ?? {};
  const props = sch.properties ?? {};
  const required = new Set(Array.isArray(sch.required) ? sch.required : []);
  const keys = Object.keys(props);
  if (keys.length === 0) {
    return "Record<string, never>"; // explicit "no inputs"
  }
  const lines = ["{"];
  for (const k of keys) {
    const p = props[k] ?? {};
    const ts = jsonSchemaToTs(p);
    const opt = required.has(k) ? "" : "?";
    if (p.description) {
      lines.push(`    /** ${escapeBlockComment(String(p.description).trim()).slice(0, 200)} */`);
    }
    lines.push(`    ${tsIdent(k)}${opt}: ${ts};`);
  }
  lines.push("  }");
  return lines.join("\n");
}

function main() {
  const snap = JSON.parse(readFileSync(SNAPSHOT, "utf-8"));
  const tools = Array.isArray(snap.tools) ? snap.tools : [];
  if (tools.length === 0) {
    console.error("gen-tool-types: snapshot has 0 tools — refusing to overwrite");
    process.exit(2);
  }
  // Sort deterministically — git-friendly diffs.
  tools.sort((a, b) => String(a.name).localeCompare(String(b.name)));

  const header = `// AUTO-GENERATED by frontend/scripts/gen-tool-types.mjs — DO NOT EDIT.
//
// Source: frontend/src/lib/generated/toolCatalog.snapshot.json
// Tools:  ${tools.length}
//
// Strict TS types projected from each tool's JSON Schema input_schema.
// Use ToolInputs<N> for compile-time-checked /api/invoke calls — see
// lib/typedInvoke.ts for the helper.
//
// Limits (intentional — see gen-tool-types.mjs):
//   - object-typed inputs → Record<string, unknown>
//     (nested object types are too variable across the catalog)
//   - return types: NOT generated (responses vary too much; use \`any\`
//     and validate at call sites)
//   - enums → string literal unions (drops to bare string if missing)
//
// Refresh the underlying snapshot via:  npm run sync-tools

`;

  const nameUnion = tools.map((t) => JSON.stringify(t.name)).join("\n  | ");

  const interfaceLines = tools.map((t) => {
    const inputs = buildInputsInterface(t);
    const desc = t.description ? `  /** ${escapeBlockComment(String(t.description).trim()).slice(0, 240)} */\n` : "";
    return `${desc}  ${JSON.stringify(t.name)}: ${inputs};`;
  });

  const out =
    header +
    `export type ToolName =\n  | ${nameUnion};\n\n` +
    `export interface ToolInputsMap {\n${interfaceLines.join("\n")}\n}\n\n` +
    `export type ToolInputs<N extends ToolName> = ToolInputsMap[N];\n\n` +
    `export const TOOL_NAMES: readonly ToolName[] = [\n${tools
      .map((t) => `  ${JSON.stringify(t.name)},`)
      .join("\n")}\n] as const;\n`;

  writeFileSync(OUT, out, "utf-8");
  console.log(`gen-tool-types: wrote ${tools.length} typed tools → ${OUT}`);
}

main();
